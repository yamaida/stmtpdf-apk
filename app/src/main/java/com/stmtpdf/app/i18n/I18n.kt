package com.stmtpdf.app.i18n

import android.content.Context
import java.util.Locale

/** App 支持的语言，默认英文。 */
enum class AppLang(val code: String, val short: String, val label: String) {
    EN("en", "EN", "English"),
    ZH_CN("zh_CN", "中", "Chinese (Simplified)"),
    ZH_TW("zh_TW", "繁", "Chinese (Traditional)"),
    ES("es", "ES", "Spanish"),
    FR("fr_CA", "FR", "French (Canada)"),
    FR_FR("fr_FR", "FR", "French (France)"),
    PT_BR("pt_BR", "PT", "Portuguese (Brazil)"),
    DE("de_DE", "DE", "German"),
    JA("ja_JP", "JA", "Japanese");

    companion object {
        fun from(code: String?): AppLang = entries.firstOrNull { it.code == code } ?: EN

        /** 首次启动无保存时，按设备系统语言/地区自动匹配。 */
        fun fromSystem(): AppLang {
            val loc = Locale.getDefault()
            val lang = loc.language.lowercase()
            val country = loc.country.uppercase()
            return when {
                lang == "zh" && country in setOf("TW", "HK", "MO") -> ZH_TW
                lang == "zh" -> ZH_CN
                lang == "es" -> ES
                lang == "fr" && country == "CA" -> FR
                lang == "fr" -> FR_FR
                lang == "pt" -> PT_BR
                lang == "de" -> DE
                lang == "ja" -> JA
                else -> EN
            }
        }
    }
}

object LocaleStore {

    private const val PREFS = "stmtpdf_locale"
    private const val KEY = "lang"

    fun load(context: Context): AppLang {
        val saved = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, null)
        return if (saved != null) AppLang.from(saved) else AppLang.fromSystem()
    }

    fun save(context: Context, lang: AppLang) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().putString(KEY, lang.code).apply()
    }
}

